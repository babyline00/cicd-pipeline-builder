/**
 * Pure YAML compiler. Turns a pipeline graph into a GitHub Actions YAML
 * string. No external YAML library is used — the output is a hand-rolled
 * string with deterministic indentation so it can be diffed/stable.
 *
 * Smart caching is automatic:
 *   - setup-node   always emits `cache: 'npm'` (or yarn/pnpm per prop)
 *   - setup-python always emits `cache: 'pip'` (or poetry/pipenv)
 *   - setup-go     emits `cache: true` when cache manager != 'none'
 *
 * Matrix expansion: when any setup or test node declares a `matrix` axis, the
 * compiler collects all axes, emits a `strategy.matrix` block at the job
 * level, and references `${{ matrix.axis }}` in the relevant steps.
 *
 * Secrets: deploy/notify steps that reference a secret name render the
 * reference as `${{ secrets.NAME }}`. A "Required secrets" comment is
 * appended at the end of the file when the caller passes a secrets list.
 */

import type { PipelineGraph, PipelineNode } from "./node-types"
import { getNodeType } from "./node-types"
import { topologicalSort } from "./graph-validator"
import { collectMatrixAxes } from "./matrix"
import { formatSecretsRef, extractSecretRefs } from "./secrets"

export interface SecretRef {
  name: string
  description?: string
}

export function compileToYaml(
  graph: PipelineGraph,
  secrets: SecretRef[] = [],
): string {
  const lines: string[] = []
  lines.push(`# Generated by AI-Powered CI/CD Pipeline Builder`)
  lines.push(`# Pipeline graph compiled to GitHub Actions YAML.`)
  lines.push(``)
  lines.push(`name: CI`)
  lines.push(``)

  // ---- on: ----
  const trigger = graph.nodes.find((n) => n.type === "trigger")
  if (trigger) {
    const events =
      Array.isArray(trigger.props.events) && trigger.props.events.length > 0
        ? trigger.props.events
        : ["push"]
    const branch = trigger.props.branch || "main"
    lines.push(`on:`)
    for (const ev of events) {
      if (ev === "schedule") {
        lines.push(`  schedule:`)
        lines.push(`    - cron: '0 0 * * *'`)
      } else if (ev === "workflow_dispatch") {
        lines.push(`  workflow_dispatch:`)
      } else if (ev === "issues" || ev === "release" || ev === "watch") {
        lines.push(`  ${ev}:`)
      } else {
        lines.push(`  ${ev}:`)
        lines.push(`    branches: [${branch}]`)
      }
    }
    lines.push(``)
  } else {
    lines.push(`on: [push]`)
    lines.push(``)
  }

  // ---- jobs: ----
  lines.push(`jobs:`)
  lines.push(`  build:`)
  lines.push(`    runs-on: ubuntu-latest`)

  // collect matrix axes across all nodes
  const matrixAxes = collectMatrixAxes(graph.nodes)
  if (Object.keys(matrixAxes).length > 0) {
    lines.push(`    strategy:`)
    lines.push(`      matrix:`)
    for (const [k, v] of Object.entries(matrixAxes)) {
      const arr = v
        .map((x) => (typeof x === "string" ? `'${x}'` : String(x)))
        .join(", ")
      lines.push(`        ${k}: [${arr}]`)
    }
  }

  lines.push(`    permissions:`)
  lines.push(`      contents: read`)
  lines.push(`    steps:`)

  // compile each node in topological order (excluding the trigger)
  const ordered = topologicalSort(graph).filter((n) => n.type !== "trigger")
  for (const node of ordered) {
    const stepYaml = compileNode(node, matrixAxes)
    if (stepYaml) lines.push(stepYaml)
  }

  // required secrets comment block
  const referenced = extractSecretRefs(lines.join("\n"))
  const allSecrets =
    secrets.length > 0
      ? secrets
      : referenced.map((name) => ({ name }))
  if (allSecrets.length > 0) {
    lines.push(``)
    lines.push(`# Required secrets (configure in repo settings > secrets):`)
    for (const s of allSecrets) {
      lines.push(
        `# - ${s.name}${s.description ? `: ${s.description}` : ""}`,
      )
    }
  }

  return lines.join("\n") + "\n"
}

export function compileNode(
  node: PipelineNode,
  matrixAxes: Record<string, (string | number)[]> = {},
): string {
  const def = getNodeType(node.type)
  const name = def?.label ?? node.type
  const lines: string[] = []
  switch (node.type) {
    case "checkout": {
      lines.push(`      - name: Checkout`)
      lines.push(`        uses: actions/checkout@v4`)
      const withLines: string[] = []
      if (node.props.ref && node.props.ref !== "${{ github.ref }}") {
        withLines.push(`          ref: ${node.props.ref}`)
      }
      if (
        typeof node.props.fetchDepth === "number" &&
        node.props.fetchDepth !== 1
      ) {
        withLines.push(`          fetch-depth: ${node.props.fetchDepth}`)
      }
      if (withLines.length > 0) {
        lines.push(`        with:`)
        lines.push(...withLines)
      }
      break
    }
    case "setup-node": {
      lines.push(`      - name: Setup Node.js`)
      lines.push(`        uses: actions/setup-node@v4`)
      lines.push(`        with:`)
      const nodeVersion = matrixAxes["node-version"]
        ? "${{ matrix.node-version }}"
        : `'${node.props.nodeVersion ?? "20"}'`
      lines.push(`          node-version: ${nodeVersion}`)
      // Smart caching: always emit cache hint (default 'npm')
      lines.push(`          cache: '${node.props.cache ?? "npm"}'`)
      break
    }
    case "setup-python": {
      lines.push(`      - name: Setup Python`)
      lines.push(`        uses: actions/setup-python@v5`)
      lines.push(`        with:`)
      const pyVer = matrixAxes["python-version"]
        ? "${{ matrix.python-version }}"
        : `'${node.props.pythonVersion ?? "3.11"}'`
      lines.push(`          python-version: ${pyVer}`)
      lines.push(`          cache: '${node.props.cache ?? "pip"}'`)
      break
    }
    case "setup-go": {
      lines.push(`      - name: Setup Go`)
      lines.push(`        uses: actions/setup-go@v5`)
      lines.push(`        with:`)
      const goVer = matrixAxes["go-version"]
        ? "${{ matrix.go-version }}"
        : `'${node.props.goVersion ?? "1.21"}'`
      lines.push(`          go-version: ${goVer}`)
      if (node.props.cache && node.props.cache !== "none") {
        lines.push(`          cache: true`)
      }
      break
    }
    case "install": {
      lines.push(`      - name: Install dependencies`)
      lines.push(`        run: ${node.props.command ?? "npm ci"}`)
      break
    }
    case "lint": {
      lines.push(`      - name: Lint`)
      lines.push(`        run: ${node.props.command ?? "npm run lint"}`)
      break
    }
    case "test": {
      lines.push(`      - name: Test`)
      lines.push(`        run: ${node.props.command ?? "npm test"}`)
      break
    }
    case "build": {
      lines.push(`      - name: Build`)
      lines.push(`        run: ${node.props.command ?? "npm run build"}`)
      break
    }
    case "deploy-vercel": {
      const tokenRef = formatSecretsRef(
        node.props.token ?? "VERCEL_TOKEN",
      )
      const prodFlag = node.props.prod !== false ? "--prod " : ""
      lines.push(`      - name: Deploy to Vercel`)
      lines.push(
        `        run: vercel deploy ${prodFlag}--token ${tokenRef}`,
      )
      break
    }
    case "deploy-fly": {
      const tokenRef = formatSecretsRef(
        node.props.token ?? "FLY_API_TOKEN",
      )
      lines.push(`      - name: Deploy to Fly.io`)
      lines.push(`        env:`)
      lines.push(`          FLY_API_TOKEN: ${tokenRef}`)
      lines.push(`        run: fly deploy --remote-only`)
      break
    }
    case "deploy-aws": {
      const akRef = formatSecretsRef(
        node.props.accessKeyId ?? "AWS_ACCESS_KEY_ID",
      )
      const skRef = formatSecretsRef(
        node.props.secretAccessKey ?? "AWS_SECRET_ACCESS_KEY",
      )
      lines.push(`      - name: Configure AWS credentials`)
      lines.push(`        uses: aws-actions/configure-aws-credentials@v4`)
      lines.push(`        with:`)
      lines.push(`          aws-access-key-id: ${akRef}`)
      lines.push(`          aws-secret-access-key: ${skRef}`)
      lines.push(`          aws-region: ${node.props.region ?? "us-east-1"}`)
      lines.push(
        `      - name: Deploy to AWS (${node.props.service ?? "ecs"})`,
      )
      lines.push(
        `        run: aws deploy push --cluster default --service ${node.props.service ?? "ecs"}`,
      )
      break
    }
    case "notify-slack": {
      const webhookRef = formatSecretsRef(
        node.props.webhook ?? "SLACK_WEBHOOK_URL",
      )
      lines.push(`      - name: Notify Slack`)
      lines.push(`        uses: slackapi/slack-post@v1`)
      lines.push(`        with:`)
      lines.push(`          webhook-url: ${webhookRef}`)
      lines.push(`          channel: ${node.props.channel ?? "#deployments"}`)
      break
    }
    case "notify-email": {
      lines.push(`      - name: Notify Email`)
      lines.push(`        run: |`)
      lines.push(
        `          echo "Sending email to ${node.props.to ?? "(unset)"} subject: ${node.props.subject ?? "Pipeline complete"}"`,
      )
      lines.push(`          # (mock) — wire up to your email provider of choice`)
      break
    }
    default: {
      lines.push(`      - name: ${name}`)
      lines.push(`        run: echo "Unknown step: ${node.type}"`)
    }
  }
  return lines.join("\n")
}

/**
 * Sanity-check the YAML output without a full YAML parser. Verifies the key
 * sections (name, on, jobs, runs-on, steps) are present and the indentation
 * looks consistent. Returns `{ ok, reason? }`.
 */
export function assertYamlLooksValid(yaml: string): {
  ok: boolean
  reason?: string
} {
  if (typeof yaml !== "string" || yaml.length === 0)
    return { ok: false, reason: "empty" }
  if (!/^name:\s+\S+/m.test(yaml))
    return { ok: false, reason: "missing name:" }
  if (!/^on:/m.test(yaml)) return { ok: false, reason: "missing on:" }
  if (!/^jobs:/m.test(yaml)) return { ok: false, reason: "missing jobs:" }
  if (!/runs-on:\s+ubuntu-latest/m.test(yaml))
    return { ok: false, reason: "missing runs-on" }
  if (!/steps:/m.test(yaml)) return { ok: false, reason: "missing steps:" }
  return { ok: true }
}
